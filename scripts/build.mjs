// Assemble ordinary HTML at build time. Browsers receive the complete page.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, sep } from 'node:path';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));

// styles.css is a list of @imports, which browsers fetch one after another. Give the
// page one <link> per file instead so they download in parallel, in the same order.
async function expandStylesheets(html, publicRoot) {
  const link = /^([\t ]*)<link rel="stylesheet" href="styles\.css">[\t ]*$/m;
  const match = link.exec(html);
  if (!match) return html;
  let entry;
  try { entry = await readFile(resolve(publicRoot, 'styles.css'), 'utf8'); }
  catch (error) { if (error.code === 'ENOENT') return html; throw error; }
  const files = [...entry.matchAll(/^@import url\("([\w/.-]+\.css)"\);/gm)].map(([, file]) => file);
  if (!files.length) return html;
  const links = files.map(file => `${match[1]}<link rel="stylesheet" href="${file}">`).join('\n');
  return html.slice(0, match.index) + links + html.slice(match.index + match[0].length);
}

export async function renderPage(root = projectRoot) {
  const publicRoot = resolve(root, 'public');
  const template = await readFile(resolve(root, 'src/index.html'), 'utf8');
  const includes = [...template.matchAll(/^([\t ]*)<!-- include: ([\w/.-]+\.html) -->[\t ]*$/gm)];
  let html = template;
  // Reverse order keeps each replacement's offsets stable.
  for (const match of includes.reverse()) {
    const [, indent, relativePath] = match;
    const path = resolve(publicRoot, relativePath);
    if (!path.startsWith(publicRoot + sep)) throw new Error(`Include is outside public/: ${relativePath}`);
    const fragment = await readFile(path, 'utf8');
    if (fragment.includes('<!-- include:')) throw new Error(`Nested includes are unsupported: ${relativePath}`);
    const content = fragment.trimEnd().split('\n').map(line => indent + line).join('\n');
    html = html.slice(0, match.index) + content + html.slice(match.index + match[0].length);
  }
  if (html.includes('<!-- include:')) throw new Error('Invalid include in src/index.html; use <!-- include: modules/name/section.html --> on its own line.');
  html = await expandStylesheets(html, publicRoot);
  return html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by npm run build. Edit src/index.html and public/modules/ instead. -->');
}

export async function buildPage(root = projectRoot) {
  const html = await renderPage(root);
  await writeFile(resolve(root, 'public/index.html'), html);
  return html;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildPage();
  console.log('Built public/index.html from the page modules.');
}
